use lisan::Interpreter;

fn run(source: &str) -> Result<Vec<String>, String> {
    Interpreter::default().run_source(source)
}

#[test]
fn test_arduino_stdlib_and_simulation() {
    let src = r#"
استورد "اردوينو"

دع سيرفو = جديد محرك_سيرفو(9)
اطبع(سيرفو.حرك(120))

دع مسافة = جديد حساس_مسافة(4، 5)
مسافة.ضبط_محاكاة(12)
اطبع(مسافة.اقرأ_سم())
اطبع(مسافة.هل_قريب(15))

دع حرارة = جديد حساس_حرارة(7، "DHT22")
حرارة.ضبط_محاكاة(28.5، 60.0)
اطبع(حرارة.اقرأ_حرارة())
اطبع(حرارة.اقرأ_رطوبة())

دع شاشة = جديد شاشة_كريستال(16، 2)
شاشة.اطبع_في(0، 0، "لسان أردوينو")
اطبع(شاشة.محتوى_السطر(0))

دع واي = جديد واي_فاي_متحكم()
واي.اتصل("MyWiFi"، "pass")
اطبع(واي.هل_متصل())
اطبع(واي.عنوان_ip())
"#;
    let out = run(src).unwrap();
    assert_eq!(
        out,
        [
            "120",
            "12",
            "صحيح",
            "28.5",
            "60",
            "لسان أردوينو",
            "صحيح",
            "192.168.1.105"
        ]
    );
}

#[test]
fn test_arduino_transpilation_builtin() {
    let src = r#"
دع كود_المتحكم = "دالة إعداد() { تسلسلي_ابدأ(115200)؛ وضع_المنفذ(13، \"مخرج\") }\nدالة تكرار() { اكتب_رقمي(13، 1)؛ انتظر_ملي(250) }"
دع ملف_ino = ترجم_أردوينو(كود_المتحكم)
اطبع(ملف_ino.تحتوي("void setup()"))
اطبع(ملف_ino.تحتوي("Serial.begin(115200)"))
اطبع(ملف_ino.تحتوي("digitalWrite(13, HIGH)"))
"#;
    let out = run(src).unwrap();
    assert_eq!(out, ["صحيح", "صحيح", "صحيح"]);
}

