use lisan::Interpreter;

fn run(source: &str) -> Result<Vec<String>, String> {
    Interpreter::default().run_source(source)
}

#[test]
fn test_class_definition_and_constructor() {
    let src = r#"
صنف مستخدم {
    دالة بناء(اسم، عمر) {
        هذا.اسم = اسم
        هذا.عمر = عمر
    }

    دالة تحية() {
        أرجع "مرحباً يا " + هذا.اسم
    }
}

دع م = مستخدم("زيد"، 28)
اطبع(م.اسم)
اطبع(م.عمر)
اطبع(م.تحية())
اطبع(نوع(م))
"#;
    let out = run(src).unwrap();
    assert_eq!(out, ["زيد", "28", "مرحباً يا زيد", "مستخدم"]);
}

#[test]
fn test_new_keyword_and_property_mutation() {
    let src = r#"
هيكل حساب {
    دالة بناء(رصيد_أولي) {
        هذا.رصيد = رصيد_أولي
    }

    دالة إيداع(مبلغ) {
        هذا.رصيد = هذا.رصيد + مبلغ
        أرجع هذا.رصيد
    }

    دالة سحب(مبلغ) {
        إذا (مبلغ > هذا.رصيد) {
            أرجع خطأ
        }
        هذا.رصيد = هذا.رصيد - مبلغ
        أرجع صحيح
    }
}

دع ح = جديد حساب(1000)
ح.إيداع(500)
اطبع(ح.رصيد)
دع نجاح = ح.سحب(200)
اطبع(نجاح)
اطبع(ح.رصيد)
"#;
    let out = run(src).unwrap();
    assert_eq!(out, ["1500", "صحيح", "1300"]);
}

#[test]
fn test_fluent_string_methods() {
    let src = r#"
دع رسالة = "مرحبا بالعالم"
اطبع(رسالة.طول())
اطبع(رسالة.تحتوي("العالم"))
اطبع(رسالة.تحتوي("شمس"))

دع كلمات = "تفاح،برتقال،موز"
اطبع(كلمات.تقسيم("،"))

دع نص_معكوس = "لسان".عكس()
اطبع(نص_معكوس)

دع مبدل = "أهلاً بك".استبدل("بك", "بالجميع")
اطبع(مبدل)
"#;
    let out = run(src).unwrap();
    assert_eq!(out[0], "13");
    assert_eq!(out[1], "صحيح");
    assert_eq!(out[2], "خطأ");
    assert_eq!(out[3], "[\"تفاح\"، \"برتقال\"، \"موز\"]");
    assert_eq!(out[4], "ناسل");
    assert_eq!(out[5], "أهلاً بالجميع");
}

#[test]
fn test_fluent_list_and_map_methods() {
    let src = r#"
دع أرقام = [5، 2، 9، 1]
اطبع(أرقام.طول())
اطبع(أرقام.مجموع())
اطبع(أرقام.فرز())
اطبع(أرقام.عكس())

دع مضافة = [10، 20].أضف(30)
اطبع(مضافة)

دع قاموس_بيانات = {"الاسم": "أحمد"، "العمر": 30}
اطبع(قاموس_بيانات.حجم())
اطبع(قاموس_بيانات.مفاتيح())
اطبع(قاموس_بيانات.قيم())
"#;
    let out = run(src).unwrap();
    assert_eq!(out[0], "4");
    assert_eq!(out[1], "17");
    assert_eq!(out[2], "[1، 2، 5، 9]");
    assert_eq!(out[3], "[1، 9، 2، 5]");
    assert_eq!(out[4], "[10، 20، 30]");
    assert_eq!(out[5], "2");
    assert_eq!(out[6], "[\"الاسم\"، \"العمر\"]");
    assert_eq!(out[7], "[\"أحمد\"، 30]");
}

