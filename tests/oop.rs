#[test]
fn test_class_inheritance_and_super() {
    let src = r#"
صنف مركبة {
    دالة بناء(اسم) {
        هذا.اسم = اسم
    }

    دالة وصف() {
        أرجع "مركبة: " + هذا.اسم
    }
}

صنف سيارة_سباق يرث مركبة {
    دالة بناء(اسم، سرعة_قصوى) {
        أصل.بناء(اسم)
        هذا.سرعة_قصوى = سرعة_قصوى
    }

    دالة تفاصيل() {
        أرجع هذا.وصف() + " بسرعة " + نص(هذا.سرعة_قصوى)
    }
}

دع س = جديد سيارة_سباق("صقر"، 320)
اطبع(س.اسم)
اطبع(س.وصف())
اطبع(س.تفاصيل())
"#;
    let out = run(src).unwrap();
    assert_eq!(out, ["صقر", "مركبة: صقر", "مركبة: صقر بسرعة 320"]);
}

#[test]
fn test_lambda_and_higher_order_list_methods() {
    let src = r#"
دع مضاعفة = دالة(س) => س * 2
اطبع(مضاعفة(7))

دع قائمة = [1، 2، 3، 4، 5]
دع مربعات = قائمة.طبق(دالة(ن) => ن * ن)
اطبع(مربعات)

دع كبار = قائمة.رشح(دالة(ن) => ن > 2)
اطبع(كبار)

دع حاصل_جمع = قائمة.اختزل(0، دالة(تراكم، عنصر) => تراكم + عنصر)
اطبع(حاصل_جمع)
"#;
    let out = run(src).unwrap();
    assert_eq!(out[0], "14");
    assert_eq!(out[1], "[1، 4، 9، 16، 25]");
    assert_eq!(out[2], "[3، 4، 5]");
    assert_eq!(out[3], "15");
}

