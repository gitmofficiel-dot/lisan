#[test]
fn test_foreach_unpacking() {
    let code = r#"
    دع أزواج = [[1, "واحد"], [2, "اثنان"]]
    دع كودات = []
    دع كلمات = []
    لكل كود، كلمة في أزواج {
        ألحق(كودات، كود)
        ألحق(كلمات، كلمة)
    }
    تحقق_يساوي(كودات, [1, 2])
    تحقق_يساوي(كلمات, ["واحد", "اثنان"])

    دع قاموس = {"س": 100, "ص": 200}
    دع مفاتيح = []
    لكل مفتاح، قيمة في قاموس.عناصر() {
        ألحق(مفاتيح، مفتاح)
    }
    تحقق_صحيح("س" في مفاتيح)
    تحقق_صحيح("ص" في مفاتيح)

    دع مدموج = []
    لكل ح، ر في سحاب(["أ", "ب"], [10, 20]) {
        ألحق(مدموج، ح + نص(ر))
    }
    تحقق_يساوي(مدموج, ["أ10", "ب20"])

    دع معدود = []
    لكل ترقيم، عنصر في مرقم(["تفاح", "موز"]) {
        ألحق(معدود، [ترقيم، عنصر])
    }
    تحقق_يساوي(معدود, [[0, "تفاح"], [1, "موز"]])
    "#;
    if let Err(e) = run(code) {
        panic!("Foreach unpacking test failed: {}", e);
    }
}

#[test]
fn test_context_manager_with() {
    let code = r#"
    صنف مورد {
        دالة بناء(اسم) {
            هذا.اسم = اسم
            هذا.الحالة = "مغلق"
        }
        دالة ادخل() {
            هذا.الحالة = "مفتوح"
            أرجع هذا
        }
        دالة اخرج() {
            هذا.الحالة = "مغلق"
        }
    }

    دع كائن = مورد("قاعدة_بيانات")
    تحقق_يساوي(كائن.الحالة, "مغلق")

    مع كائن كـ متصل {
        تحقق_يساوي(متصل.الحالة, "مفتوح")
        تحقق_يساوي(متصل.اسم, "قاعدة_بيانات")
    }

    تحقق_يساوي(كائن.الحالة, "مغلق")

    دع مسار = "/tmp/lisan_parity_test.txt"
    مع افتح(مسار, "ك") كـ م {
        م.اكتب("مرحبا يا لسان")
    }

    مع افتح(مسار, "ق") كـ م {
        دع نص_الملف = م.اقرأ()
        تحقق_يساوي(نص_الملف, "مرحبا يا لسان")
    }
    "#;
    if let Err(e) = run(code) {
        panic!("Context manager test failed: {}", e);
    }
}

#[test]
fn test_varargs() {
    let code = r#"
    دالة مجموع_شامل(*أرقام) {
        دع إجمالي = 0
        لكل ر في أرقام {
            إجمالي = إجمالي + ر
        }
        أرجع إجمالي
    }

    تحقق_يساوي(مجموع_شامل(), 0)
    تحقق_يساوي(مجموع_شامل(1, 2, 3), 6)
    تحقق_يساوي(مجموع_شامل(10, 20, 30, 40), 100)

    دالة منسق(بادئة، *عناصر) {
        أرجع بادئة + ": " + نص(طول(عناصر))
    }
    تحقق_يساوي(منسق("العدد"), "العدد: 0")
    تحقق_يساوي(منسق("القيم", "أ", "ب", "ج"), "القيم: 3")
    "#;
    if let Err(e) = run(code) {
        panic!("Varargs test failed: {}", e);
    }
}

