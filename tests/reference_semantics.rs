use lisan::run;

#[test]
fn test_list_reference_semantics() {
    let code = r#"
    دع أ = [10, 20]
    دع ب = أ
    ب.أضف(30)
    تحقق_يساوي(أ, [10, 20, 30])
    تحقق_يساوي(طول(أ), 3)

    ب[0] = 99
    تحقق_يساوي(أ[0], 99)

    ب.احذف(1)
    تحقق_يساوي(أ, [99, 30])

    ب.أدرج(1, 55)
    تحقق_يساوي(أ, [99, 55, 30])

    دع نسخة = أ.نسخ()
    نسخة.أضف(100)
    تحقق_يساوي(طول(أ), 3)
    تحقق_يساوي(طول(نسخة), 4)

    أ.مسح()
    تحقق_يساوي(طول(أ), 0)
    تحقق_يساوي(طول(ب), 0)
    "#;
    assert!(run(code).is_ok());
}

#[test]
fn test_map_reference_semantics() {
    let code = r#"
    دع م1 = {"س": 1, "ص": 2}
    دع م2 = م1
    م2["س"] = 100
    تحقق_يساوي(م1["س"], 100)

    م2.أضف("ع", 300)
    تحقق_يساوي(م1["ع"], 300)
    تحقق_صحيح(م1.يحتوي("ع"))

    م2.احذف("ص")
    تحقق_خطأ(م1.يحتوي("ص"))

    دع نسخة = م1.نسخ()
    نسخة["س"] = 999
    تحقق_يساوي(م1["س"], 100)
    تحقق_يساوي(نسخة["س"], 999)

    م1.مسح()
    تحقق_يساوي(طول(م1), 0)
    تحقق_يساوي(طول(م2), 0)
    "#;
    if let Err(e) = run(code) {
        panic!("Map test failed: {}", e);
    }
}

